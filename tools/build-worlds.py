"""Bundle the authored JSON layouts as a classic script for offline file:// play."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
packs = {}
for name in (
    "Coral Coast",
    "Amber Dunes", "Willow River", "Hushwood Forest", "Copperbrush Meadow", "Monstera Gardens", "Yellowstone Highlands",
):
    folder = root / name
    manifest = json.loads((folder / "world.json").read_text())
    manifest["levels"] = [
        {**json.loads((folder / entry["layout"]).read_text()),
         **({"background": entry["background"], "backgroundFit": entry.get("backgroundFit", "repeat")} if "background" in entry else {})}
        for entry in manifest["levels"]
    ]
    packs[name] = manifest

(root / "worlds.js").write_text(
    "// Generated by tools/build-worlds.py from the authored world packs.\n"
    + "const authoredWorlds = "
    + json.dumps(packs, ensure_ascii=False, separators=(",", ":"))
    + ";\nconst trailArt = "
    + json.dumps(json.loads((root / "assets/level-art/manifest.json").read_text()), separators=(",", ":"))
    + ";\nconst trailLandmarks = "
    + json.dumps(json.loads((root / "assets/trail/regions.json").read_text()), separators=(",", ":"))
    + ";\nconst spriteFeet = "
    + json.dumps(json.loads((root / "assets/trail/foot-anchors.json").read_text()), separators=(",", ":"))
    + ";\nconst trailAnimations = "
    + json.dumps(json.loads((root / "assets/trail/animations.json").read_text()), separators=(",", ":"))
    + ";\n"
)
